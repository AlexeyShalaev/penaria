from functools import partial

import pytest
from alembic import command

from penaria.apps.migrate.__main__ import parse_command

pytestmark = pytest.mark.unit


def test_upgrade_goes_to_head_by_default() -> None:
    parsed = parse_command(["upgrade"])

    assert isinstance(parsed, partial)
    assert parsed.func is command.upgrade
    assert parsed.keywords == {"revision": "head"}


def test_revision_autogenerates_unless_asked_for_an_empty_one() -> None:
    autogenerated = parse_command(["revision", "-m", "add homes"])
    empty = parse_command(["revision", "-m", "add homes", "--empty"])

    assert isinstance(autogenerated, partial)
    assert isinstance(empty, partial)
    assert autogenerated.keywords == {"message": "add homes", "autogenerate": True}
    assert empty.keywords == {"message": "add homes", "autogenerate": False}


def test_a_command_is_required() -> None:
    with pytest.raises(SystemExit):
        parse_command([])
